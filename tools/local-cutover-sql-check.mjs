import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

// Real PostgreSQL execution with synthetic users/storage/cron; no production access.
const source = readFileSync(new URL('./inspect-local-cutover.py', import.meta.url), 'utf8');
const sql = source.match(/SQL = r"""([\s\S]*?)"""/)[1];
const db = new PGlite();
await db.exec(`
  CREATE SCHEMA auth; CREATE SCHEMA storage; CREATE SCHEMA cron;
  CREATE TABLE auth.users(id int PRIMARY KEY);
  CREATE TABLE public.users(user_id int PRIMARY KEY, auth_id int, status text);
  CREATE TABLE public.no_pk(value text);
  CREATE TABLE public.system_settings(key text PRIMARY KEY,value text);
  INSERT INTO public.system_settings VALUES('line_channel_token','PRIVATE-SYNTHETIC');
  CREATE TABLE storage.buckets(id text PRIMARY KEY, public boolean);
  CREATE TABLE storage.objects(id int, bucket_id text, metadata jsonb);
  CREATE TABLE cron.job(jobid int, schedule text, active boolean, command text);
  INSERT INTO auth.users VALUES(1),(2),(3);
  INSERT INTO public.users VALUES(1,1,'active'),(2,null,'active'),(3,99,'inactive'),(4,1,'active');
  INSERT INTO storage.buckets VALUES('private-files',false),('empty-bucket',false);
  INSERT INTO storage.objects VALUES(1,'private-files','{"size":123}'),(2,'private-files','{"size":"invalid"}');
  INSERT INTO cron.job VALUES(1,'*/5 * * * *',true,'SELECT 1');
`);
const results = [];
try {
  // psql's gexec executes SQL generated by the immediately preceding query.
  const blocks = sql.split(/\\gexec\s*/);
  for (let index = 0; index < blocks.length; index++) {
    const statements = await db.exec(blocks[index]);
    if (index < blocks.length - 1) {
      const generated = statements.pop();
      for (const row of generated.rows) {
        results.push(...await db.exec(Object.values(row)[0]));
      }
    }
    results.push(...statements);
  }
  const rows = results.flatMap(result => result.rows).map(row => Object.values(row)[0]);
  const auth = rows.find(row => row.section === 'auth');
  assert.equal(rows.find(row => row.key === 'line_channel_token').state, 'set');
  assert.equal(rows.find(row => row.key === 'line_group_id').state, 'missing');
  assert.equal(JSON.stringify(rows).includes('PRIVATE-SYNTHETIC'), false);
  assert.equal(auth.activeWithoutAuth, 1);
  assert.equal(auth.danglingAuthLinks, 1);
  assert.equal(auth.authWithoutPublic, 2);
  assert.equal(auth.duplicateAuthLinks, 1);
  assert.equal(rows.find(row => row.bucket === 'private-files').metadataBytes, 123);
  assert.equal(rows.find(row => row.bucket === 'empty-bucket').objects, 0);
  assert.equal(rows.find(row => row.section === 'table' && row.name === 'no_pk').primaryKey, false);
  assert.equal(rows.find(row => row.section === 'rows' && row.table === 'users').count, 4);
  assert.equal(rows.filter(row => row.section === 'cron').length, 1);
  assert.equal((await db.query('SELECT count(*) AS n FROM public.users')).rows[0].n, 4);
  await db.exec('DROP SCHEMA cron CASCADE');
  const fallback = sql.match(/SELECT CASE WHEN to_regclass\('cron.job'\)[\s\S]*?END/)[0];
  const generated = await db.query(fallback);
  const noCron = await db.query(Object.values(generated.rows[0])[0]);
  assert.equal(Object.values(noCron.rows[0])[0].available, false);
  console.log('Local cutover SQL: auth gaps, storage totals, PK coverage, counts and optional cron passed.');
} finally {
  await db.close();
}
